from datetime import date, datetime
from typing import Optional

from pydantic import BaseModel, ConfigDict, EmailStr, Field, field_validator


# Keep these identical to the lists in app.py
EXPENSE_CATEGORIES = {
    "Food",
    "Transport",
    "Data",
    "Printing",
    "Accommodation",
    "Other",
}

WEEKS = {
    "Week 1",
    "Week 2",
    "Week 3",
    "Week 4",
}

# Was imported from ui.py, which pulls the Streamlit frontend into the backend. Defined here instead.
FEEDBACK_TYPES = {
    "Bug report",
    "Suggestion",
    "Compliment",
    "Other",
}

UNIVERSITIES = {
    "Midlands State University",
    "University of Zimbabwe",
    "National University of Science and Technology",
    "Harare Institute of Technology",
    "Great Zimbabwe University",
}

# University value for accounts created through Google until the user picks one
UNSET_UNIVERSITY = "Not set"


# ---------- Auth ----------

class UserRegisterSchema(BaseModel):
    name: str = Field(..., min_length=2, max_length=100)
    email: EmailStr
    university: str = Field(..., min_length=2, max_length=150)
    password: str = Field(..., min_length=6, max_length=128)


class UserLoginSchema(BaseModel):
    email: EmailStr
    password: str = Field(..., max_length=128)


class UserOut(BaseModel):
    name: str
    email: str
    university: str
    has_password: bool = True  # False for accounts that only sign in with Google


class LoginResponse(BaseModel):
    access_token: str
    token_type: str = "bearer"
    user: UserOut


class GoogleExchangeSchema(BaseModel):
    code: str = Field(..., min_length=10, max_length=200)


class GoogleMobileSchema(BaseModel):
    id_token: str = Field(..., min_length=20, max_length=4096)


class ProfileUpdateSchema(BaseModel):
    university: str

    @field_validator("university")
    @classmethod
    def check_university(cls, value: str) -> str:
        if value not in UNIVERSITIES:
            raise ValueError("Invalid university.")
        return value


# ---------- Budget ----------

class IncomeSchema(BaseModel):
    income: float = Field(..., ge=0.0)


class ExpenseCreateSchema(BaseModel):
    week: str
    category: str
    amount: float = Field(..., gt=0.0)
    # UUID generated by the app; lets the server ignore a retried upload
    client_id: Optional[str] = Field(None, min_length=8, max_length=64)

    @field_validator("week")
    @classmethod
    def check_week(cls, value: str) -> str:
        if value not in WEEKS:
            raise ValueError("Invalid week.")
        return value

    @field_validator("category")
    @classmethod
    def check_category(cls, value: str) -> str:
        if value not in EXPENSE_CATEGORIES:
            raise ValueError("Invalid expense category.")
        return value


class BudgetEntrySchema(ExpenseCreateSchema):
    """Offline sync entry.
    The owner comes from the login token, not the client.
    """
    pass


class ExpenseOut(BaseModel):
    id: int
    client_id: Optional[str] = None
    week: str
    category: str
    amount: float


# ---------- Marketplace ----------

class MarketplaceCreateSchema(BaseModel):
    title: str = Field(..., min_length=1, max_length=120)
    price: float = Field(..., ge=0.0)
    contact: str = Field(..., min_length=1, max_length=100)


class MarketplaceOut(BaseModel):
    id: int
    title: str
    price: float
    contact: str
    seller: str
    is_mine: bool = False  # True when the signed-in user posted it (the app shows a delete button)
    timestamp: Optional[datetime] = None


# ---------- Events ----------

class EventOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    title: str
    type: str
    deadline: date


# ---------- AI ----------

class ChatPromptSchema(BaseModel):
    prompt: str = Field(..., max_length=8000)
    provider_preference: str = "gemini"
    # "gemini" or "groq"


class AskSchema(BaseModel):
    module_code: str = Field(..., min_length=1, max_length=20)
    question: str = Field(..., min_length=1, max_length=4000)


class ResultOut(BaseModel):
    result: str


# ---------- Feedback ----------

class FeedbackSchema(BaseModel):
    category: str
    message: str = Field(..., min_length=5, max_length=1000)

    @field_validator("category")
    @classmethod
    def check_category(cls, value: str) -> str:
        if value not in FEEDBACK_TYPES:
            raise ValueError("Invalid feedback type.")
        return value


# ---------- Delete Account ----------

class DeleteAccountSchema(BaseModel):
    # Password accounts send "password"; Google-only accounts send "confirm_text" ("DELETE")
    password: Optional[str] = Field(None, max_length=128)
    confirm_text: Optional[str] = Field(None, max_length=20)
